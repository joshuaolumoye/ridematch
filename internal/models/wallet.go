package models

import "time"

// Ledger account kinds. Wallet rows carry a WalletID; the others are
// platform-level pools whose balance is the sum of their entries.
const (
	AccountWallet        = "wallet"
	AccountEscrow        = "escrow"         // funds held for in-flight trips
	AccountExternalIn    = "external_in"    // money received via Flutterwave
	AccountExternalOut   = "external_out"   // money paid out via Flutterwave
	AccountPayoutPending = "payout_pending" // withdrawn from wallet, not yet confirmed by bank
	AccountFees          = "fees"           // pass-through gateway fees
)

// Wallet is one user's spendable balance, in kobo. All balance movements go
// through LedgerRepository inside a transaction holding a row lock on this
// row; the CHECK constraint is a last line of defence against ever going
// negative.
type Wallet struct {
	ImmutableBase

	UserID      string `gorm:"type:char(36);uniqueIndex;not null" json:"user_id"`
	BalanceKobo int64  `gorm:"not null;check:balance_kobo >= 0" json:"balance_kobo"`
	Currency    string `gorm:"type:char(3);not null;default:'NGN'" json:"currency"`

	// Transaction PIN for withdrawals (bcrypt).
	PINHash           string     `gorm:"type:varchar(100)" json:"-"`
	PINSetAt          *time.Time `json:"-"`
	PINFailedAttempts int        `json:"-"`
	PINLockedUntil    *time.Time `json:"-"`

	// CooldownUntil restricts withdrawals (lower cap) after a sensitive
	// change: new payout account, new/changed PIN.
	CooldownUntil *time.Time `json:"cooldown_until,omitempty"`

	// WithdrawalsFrozen blocks all payouts (admin action, or an open
	// next-of-kin appeal).
	WithdrawalsFrozen bool   `gorm:"not null" json:"withdrawals_frozen"`
	FrozenReason      string `gorm:"type:varchar(255)" json:"frozen_reason,omitempty"`
}

func (Wallet) TableName() string { return "wallets" }

// LedgerTransaction groups the entries of one money movement. Entries of a
// transaction always sum to zero. IdempotencyKey makes every movement safe
// to retry: a second attempt with the same key is a no-op.
type LedgerTransaction struct {
	ID             string    `gorm:"type:char(36);primaryKey" json:"id"`
	Kind           string    `gorm:"type:varchar(40);index;not null" json:"kind"`
	IdempotencyKey string    `gorm:"type:varchar(150);uniqueIndex;not null" json:"idempotency_key"`
	RefType        string    `gorm:"type:varchar(30);index:idx_ledger_ref,priority:1" json:"ref_type"`
	RefID          string    `gorm:"type:char(36);index:idx_ledger_ref,priority:2" json:"ref_id"`
	Description    string    `gorm:"type:varchar(255)" json:"description"`
	CreatedAt      time.Time `gorm:"index" json:"created_at"`
}

func (LedgerTransaction) TableName() string { return "ledger_transactions" }

// LedgerEntry is one signed posting. Positive = credit to the account,
// negative = debit. Rows are append-only.
type LedgerEntry struct {
	ID            uint64    `gorm:"primaryKey;autoIncrement" json:"id"`
	TransactionID string    `gorm:"type:char(36);index;not null" json:"transaction_id"`
	Account       string    `gorm:"type:varchar(20);index;not null" json:"account"`
	WalletID      *string   `gorm:"type:char(36);index:idx_entry_wallet_time,priority:1" json:"wallet_id,omitempty"`
	AmountKobo    int64     `gorm:"not null" json:"amount_kobo"`
	BalanceAfter  *int64    `json:"balance_after_kobo,omitempty"`
	CreatedAt     time.Time `gorm:"type:datetime(3);index:idx_entry_wallet_time,priority:2" json:"created_at"`
}

func (LedgerEntry) TableName() string { return "ledger_entries" }

// TopupStatus is the lifecycle of a wallet top-up.
type TopupStatus string

const (
	TopupPending    TopupStatus = "pending"
	TopupSuccessful TopupStatus = "successful"
	TopupExpired    TopupStatus = "expired"
	TopupFailed     TopupStatus = "failed"
)

// WalletTopup is one payment request: a one-time bank account number
// generated by Flutterwave that the user transfers to. The wallet is
// credited only after the webhook/verify confirms the money arrived.
type WalletTopup struct {
	ImmutableBase

	UserID string      `gorm:"type:char(36);index;not null" json:"user_id"`
	TxRef  string      `gorm:"type:varchar(100);uniqueIndex;not null" json:"tx_ref"`
	Status TopupStatus `gorm:"type:varchar(15);index;not null" json:"status"`

	// RequestedKobo is what the user wants in their wallet; FeeKobo is the
	// gross-up; GrossKobo is what they must transfer.
	RequestedKobo int64 `gorm:"not null" json:"requested_kobo"`
	FeeKobo       int64 `gorm:"not null" json:"fee_kobo"`
	GrossKobo     int64 `gorm:"not null" json:"gross_kobo"`

	AccountNumber string     `gorm:"type:varchar(20)" json:"account_number"`
	BankName      string     `gorm:"type:varchar(100)" json:"bank_name"`
	ExpiresAt     *time.Time `gorm:"index" json:"expires_at,omitempty"`

	FlwTransactionID string     `gorm:"type:varchar(50);index" json:"-"`
	PaidKobo         int64      `json:"paid_kobo"`
	CreditedKobo     int64      `json:"credited_kobo"`
	CompletedAt      *time.Time `json:"completed_at,omitempty"`
	FailureReason    string     `gorm:"type:varchar(255)" json:"failure_reason,omitempty"`
}

func (WalletTopup) TableName() string { return "wallet_topups" }

// EscrowStatus is the lifecycle of funds held for a trip.
type EscrowStatus string

const (
	EscrowHeld     EscrowStatus = "held"
	EscrowReleased EscrowStatus = "released"
	EscrowRefunded EscrowStatus = "refunded"
	EscrowDisputed EscrowStatus = "disputed"
)

// EscrowHold is the fare for one trip, moved out of the passenger's wallet
// when a driver is confirmed and into the driver's wallet when the trip
// completes (or back to the passenger if it is cancelled).
type EscrowHold struct {
	ImmutableBase

	TripID        string       `gorm:"type:char(36);uniqueIndex;not null" json:"trip_id"`
	PayerUserID   string       `gorm:"type:char(36);index;not null" json:"payer_user_id"`
	PayeeUserID   string       `gorm:"type:char(36);index;not null" json:"payee_user_id"`
	PayeeDriverID string       `gorm:"type:char(36);not null" json:"payee_driver_id"`
	AmountKobo    int64        `gorm:"not null" json:"amount_kobo"`
	Status        EscrowStatus `gorm:"type:varchar(12);index:idx_escrow_due,priority:1;not null" json:"status"`
	// Version increments each time a refunded hold is re-opened for the
	// same trip (a failed accept attempt followed by a successful one), so
	// every ledger idempotency key stays unique.
	Version int `gorm:"not null" json:"version"`

	// ReleaseAfter is set when the driver completes the trip: the passenger
	// can confirm earlier or dispute until then; afterwards it auto-releases.
	ReleaseAfter *time.Time `gorm:"index:idx_escrow_due,priority:2" json:"release_after,omitempty"`
	ReleasedAt   *time.Time `json:"released_at,omitempty"`
	RefundedAt   *time.Time `json:"refunded_at,omitempty"`

	DisputeReason string     `gorm:"type:varchar(500)" json:"dispute_reason,omitempty"`
	DisputedAt    *time.Time `json:"disputed_at,omitempty"`
	Resolution    string     `gorm:"type:varchar(500)" json:"resolution,omitempty"`
	ResolvedBy    string     `gorm:"type:char(36)" json:"resolved_by,omitempty"`
}

func (EscrowHold) TableName() string { return "escrow_holds" }
